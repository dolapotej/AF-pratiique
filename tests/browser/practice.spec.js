test('writing, model answer, rubric and textbook project persist', async ({ page }, info) => {
  await page.goto('/')
  await open(page, 'messages')
  await page.locator('#tab-write').click()
  await expect(page.locator('#activity-panel')).toContainText('Demander des idées de sortie')
  await page.locator('#writing-answer').fill('<b>Premier exercice</b>')
  await page.locator('#task-answer').fill('Bonjour, je voudrais le programme du dimanche.')
  await page.locator('#toggle-model').click()
  await expect(page.locator('.model')).toContainText(lessons.find(l => l.id === 'messages').writing.model)
  await page.locator('#rubric-0').check()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('writing.png'), fullPage: true })
  await page.reload()
  await page.locator('#continue').click()
  await expect(page.locator('#writing-answer')).toHaveValue('<b>Premier exercice</b>')
  await expect(page.locator('#writing-answer b')).toHaveCount(0)
  await expect(page.locator('#task-answer')).toHaveValue('Bonjour, je voudrais le programme du dimanche.')
  await page.locator('#toggle-model').click()
  await expect(page.locator('#rubric-0')).toBeChecked()
})

test('export, validated import, cancellation and confirmed reset', async ({ page }) => {
  await page.goto('/')
  await page.locator('#continue').click()
  await page.locator('#tab-write').click()
  await page.locator('#writing-answer').fill('My saved draft')
  await page.locator('#nav-carnet').click()
  const downloadEvent = page.waitForEvent('download')
  await page.locator('#export-progress').click()
  const path = await (await downloadEvent).path()
  page.once('dialog', dialog => dialog.dismiss())
  await page.locator('#reset-progress').click()
  await expect(page.locator('#data-message')).not.toContainText('réinitialisé')
  page.once('dialog', dialog => dialog.accept())
  await page.locator('#reset-progress').click()
  await expect(page.locator('#data-message')).toContainText('réinitialisé')
  page.once('dialog', async dialog => {
    expect(dialog.message()).toContain('1 brouillon(s)')
    await dialog.accept()
  })
  await page.locator('#import-file').setInputFiles(path)
  await expect(page.locator('#data-message')).toContainText('Sauvegarde importée')
  await page.locator('#import-file').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":99}') })
  await expect(page.locator('#data-message')).toContainText('Import impossible')
  await page.locator('#nav-today').click()
  await page.locator('#continue').click()
  await expect(page.locator('#writing-answer')).toHaveValue('My saved draft')
})

test('damaged and unavailable browser storage do not stop practice', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('af-pratique-progress', 'invalid'))
  await page.reload()
  await expect(page.locator('.next-title')).toHaveText('Alphabet et accents')
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('Unavailable') } })
  await page.reload()
  await page.locator('#continue').click()
  await page.locator('#tab-write').click()
  await page.locator('#writing-answer').fill('In memory')
  await expect(page.locator('#storage-draft')).toContainText('indisponible')
  await page.locator('#tab-cards').click()
  await page.locator('#tab-write').click()
  await expect(page.locator('#writing-answer')).toHaveValue('In memory')
  await page.locator('#nav-carnet').click()
  await expect(page.locator('#storage-note')).toContainText('indisponible')
})
